# Objetivo: Receber uma temperatura em Celsius do usuário e exibir a temperatura convertida.

# Pede a temperatura em Celsius do usuário
C = float(input("Digite a temperatura em graus celsius: "))

# Calcula a temperatura em Fahrenheit
F = C * 1.8 + 32

# Mostra a temperatura em Fahrenheit
print("A temperatura em Fahrenheit é: ", F)